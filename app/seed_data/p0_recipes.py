"""Authored quick meals using the existing structured, approximate food fixtures.

Rice is already cooked and chicken is already cooked, plain, and uncoated. Potato, egg,
and salmon weights refer to the raw fixture. Water in steps is a cooking medium, not a
source of invented nutrients. Dietary tags are explicitly authored per recipe. Oat recipes
are never tagged gluten_free; no meat is labeled halal without sourcing evidence.
"""


def ingredient(code, grams, note=None):
    return {"source_food_id": f"dev_{code}", "quantity_grams": grams,
            "display_quantity": str(grams), "display_unit": "g", "preparation_note": note}


def step(instruction, phase="cook", seconds=None, timer_seconds=None):
    return {"instruction": instruction, "phase": phase, "duration_seconds": seconds,
            "timer_required": timer_seconds is not None, "timer_seconds": timer_seconds}


def recipe(name, meal_type, ingredients, steps, prep, cook, tags, equipment):
    return {"name": name, "description": f"{name}. Structured development catalog recipe; approximate fixture nutrition.",
            "servings": 1, "prep_time_minutes": prep, "cook_time_minutes": cook, "difficulty": "easy",
            "instructions_summary": " ".join(item["instruction"] for item in steps),
            "tags": [meal_type, *(["quick"] if prep + cook <= 20 else []), *tags],
            "equipment": equipment, "ingredients": ingredients, "steps": steps}


